/**
 * Robust Copy to Clipboard function
 * Tries navigator.clipboard first, falls back to document.execCommand
 */
export const copyToClipboard = async (text) => {
    if (!text) return false;
    try {
        await navigator.clipboard.writeText(text);
        return true;
    } catch (err) {
        console.warn("Navigator clipboard failed, falling back to textarea", err);
        try {
            const textArea = document.createElement("textarea");
            textArea.value = text;
            textArea.style.position = "fixed";
            textArea.style.left = "-9999px";
            document.body.appendChild(textArea);
            textArea.focus();
            textArea.select();
            const successful = document.execCommand('copy');
            document.body.removeChild(textArea);
            return successful;
        } catch (e) {
            console.error("Copy failed completely", e);
            return false;
        }
    }
};
